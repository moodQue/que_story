// Traffic attribution. One page serves every network — the link just carries ?src=
//   territory-scan.html?src=ig   (also: yt, tt, dc)
// Whitelisted so a junk/hostile value can never pollute the cohort data.
const networkAliases = {
  ig: "instagram", instagram: "instagram",
  yt: "youtube",   youtube: "youtube",
  tt: "tiktok",    tiktok: "tiktok",
  dc: "discord",   discord: "discord",
  x: "x", tw: "x",
};

const FIRST_TOUCH_KEY = "moodque_first_touch";

/**
 * Resolve which network sent this viewer.
 * Priority: ?src= → remembered first touch → referrer sniff → "direct".
 * First touch is persisted so a later bookmark/direct visit still attributes
 * to the platform that originally brought them in.
 */
function resolveNetwork() {
  const params = new URLSearchParams(location.search);
  const raw = (params.get("src") || params.get("utm_source") || "").trim().toLowerCase();

  if (networkAliases[raw]) {
    localStorage.setItem(FIRST_TOUCH_KEY, networkAliases[raw]);
    return networkAliases[raw];
  }

  const remembered = localStorage.getItem(FIRST_TOUCH_KEY);
  if (remembered) return remembered;

  // Weak fallback — in-app browsers and link-in-bio tools routinely strip this,
  // so it's a hint, never truth.
  const ref = (document.referrer || "").toLowerCase();
  if (ref.includes("instagram")) return "instagram";
  if (ref.includes("youtube") || ref.includes("youtu.be")) return "youtube";
  if (ref.includes("tiktok")) return "tiktok";
  if (ref.includes("discord")) return "discord";

  return "direct";
}

/**
 * The date to LOG the scan under — always the viewer's actual today.
 *
 * Deliberately NOT scan.date from the JSON. That file is generated by a separate job,
 * and when it went stale (frozen for 3 weeks) every scan logged under the old date —
 * which, because Firebase keys on daily_scans/{date}/{handle}, turned "one scan per
 * person per DAY" into "one scan per person EVER" (each new scan overwrote the same
 * node). Trusting our own clock means a generator failure degrades to "stale reading
 * shown" instead of silently destroying the data.
 */
function todayKey() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

/** Optional: which post/campaign drove the visit (?c=2026-07-13). */
function resolveCampaign() {
  const params = new URLSearchParams(location.search);
  const raw = (params.get("c") || params.get("utm_campaign") || "").trim();
  return raw ? raw.slice(0, 60) : null;
}

// Holds the option the viewer picked, so the save button knows what to log.
let selected = null;
let scanData = null;

function formatDate(value) {
  if (!value) return "Daily Field Report";
  const date = new Date(`${value}T12:00:00`);
  return date.toLocaleDateString(undefined, {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
}

/** Strip a leading @ and normalise, so the same person is one identity. */
function normaliseHandle(raw) {
  return (raw || "").trim().replace(/^@+/, "").toLowerCase();
}

/**
 * Firebase keys may not contain . $ # [ ] or /.
 * Using the handle as the key (rather than push()) makes the write idempotent:
 * one scan per person per day, and a re-submit overwrites instead of duplicating.
 */
function handleToKey(handle) {
  return handle.replace(/[.$#[\]/]/g, "_");
}

/** One scan per day is the point of the ritual — remember locally that we logged. */
function alreadyLoggedKey(date) {
  return `moodque_scan_${date}`;
}

/**
 * Write the scan to Firebase.
 *
 * We send the field reading the page already knows about, but MIS treats
 * mood_territory_snapshots as authoritative and re-resolves the true field
 * quadrant on sync — so a stale/odd value here can never corrupt the metric.
 */
async function saveScan() {
  const saveState = document.getElementById("save-state");
  const handleInput = document.getElementById("handle");
  const saveButton = document.getElementById("save-scan");

  if (!selected) {
    saveState.textContent = "Pick your weather first.";
    return;
  }

  const handle = normaliseHandle(handleInput.value);
  if (!handle) {
    saveState.textContent = "Add your handle so today's scan can be logged.";
    handleInput.focus();
    return;
  }

  saveButton.disabled = true;
  saveState.textContent = "Logging your scan...";

  // Log under OUR clock, not the JSON's date (see todayKey()).
  const scanDate = todayKey();

  const record = {
    // HOW it was captured (this page). Distinct from WHICH network sent them.
    source: "web",
    platform: "web",
    platform_user_id: handle, // for web, the handle IS the stable id
    viewer_handle: handle,
    referrer_network: resolveNetwork(),
    campaign: resolveCampaign(),
    scan_date: scanDate,
    self_quadrant: quadrantKeys[selected.score_key] || null,
    score_key: selected.score_key,
    raw_text: selected.label || "",
    field_territory: scanData.territory || null,
    field_quadrant: scanData.quadrant || null,
    quiz_version: scanData.quiz_version || null,
    captured_at: new Date().toISOString(),
  };

  try {
    await db.ref(`daily_scans/${scanDate}/${handleToKey(handle)}`).set(record);
    localStorage.setItem(alreadyLoggedKey(scanDate), "1");
    saveState.textContent = "Scan logged. Come back tonight and tell us if the field matched.";
    handleInput.disabled = true;
  } catch (error) {
    saveButton.disabled = false;
    saveState.textContent = "Your reading is shown above, but the scan could not be logged.";
    console.error(error);
  }
}

function renderQuiz(scan) {
  scanData = scan;

  const question = scan.questions?.[0];
  const optionsEl = document.getElementById("options");
  const resultEl = document.getElementById("result");
  const resultTitle = document.getElementById("result-title");
  const resultCopy = document.getElementById("result-copy");
  const resultContext = document.getElementById("result-context");

  document.getElementById("scan-date").textContent = formatDate(scan.date);
  document.getElementById("scan-title").textContent = scan.quiz_type === "field_scan"
    ? "Daily Field Scan"
    : "Territory Scan";
  document.getElementById("scan-prompt").textContent = question?.prompt || "Pick the signal that feels closest.";
  document.getElementById("scan-disclaimer").textContent = scan.disclaimer || "This is a daily scan, not your confirmed faction.";

  const fullScanLink = document.getElementById("full-scan-link");
  fullScanLink.href = scan.full_quiz_url || "territory.html";
  fullScanLink.textContent = scan.cta || "Take the full Territory Scan";

  optionsEl.innerHTML = "";
  for (const option of question?.options || []) {
    const button = document.createElement("button");
    button.className = "option";
    button.type = "button";
    button.setAttribute("aria-pressed", "false");
    button.innerHTML = `
      <span class="symbol">${option.symbol || ""}</span>
      <span>
        <strong>${option.label}</strong>
        <span>${scoreLabels[option.score_key] || option.score_key}</span>
      </span>
    `;

    button.addEventListener("click", () => {
      for (const el of optionsEl.querySelectorAll(".option")) {
        el.setAttribute("aria-pressed", "false");
      }
      button.setAttribute("aria-pressed", "true");
      selected = option;

      resultEl.hidden = false;
      resultTitle.textContent = option.reading || scoreLabels[option.score_key] || "Field Reading";
      resultCopy.textContent = scan.field_readings?.[option.score_key] || "Your answer is today's temporary field reading.";
      resultContext.textContent = `The field today reads ${scan.territory || "Unknown"} (${scan.quadrant || "Unknown"}).`;
      resultEl.scrollIntoView({ behavior: "smooth", block: "nearest" });
    });

    optionsEl.appendChild(button);
  }

  // If they already logged today, keep the scan usable but don't double-count.
  const saveState = document.getElementById("save-state");
  const saveButton = document.getElementById("save-scan");
  if (localStorage.getItem(alreadyLoggedKey(todayKey()))) {
    saveButton.disabled = true;
    saveState.textContent = "You've already logged today's scan. See you tomorrow.";
  }
  saveButton.addEventListener("click", saveScan);
}

async function init() {
  try {
    const response = await fetch(DATA_URL, { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    renderQuiz(await response.json());
  } catch (error) {
    document.getElementById("scan-title").textContent = "Field Scan Offline";
    document.getElementById("scan-prompt").textContent = "Today's scan data could not be loaded.";
    console.error(error);
  }
}

init();
